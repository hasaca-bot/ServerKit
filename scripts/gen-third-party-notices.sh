#!/bin/bash
#
# Generate THIRD-PARTY-NOTICES.md from the backend Python venv and the
# frontend production dependency tree. Run from the repository root:
#
#   bash scripts/gen-third-party-notices.sh
#   VENV=/path/to/venv bash scripts/gen-third-party-notices.sh
#
# Environment:
#   VENV   Python virtualenv used for the backend listing (default: backend/venv)
#
# Network access is not required when the frontend node_modules directory is
# already installed, but npx may need the registry to fetch license-checker
# on first run. A failure in the frontend step is reported and the script
# still exits non-zero so the gap is not silently shipped.

set -u

if [ ! -f "LICENSE" ] || [ ! -d "backend" ] || [ ! -d "frontend" ]; then
    echo "error: run this script from the repository root" >&2
    exit 1
fi

OUT="THIRD-PARTY-NOTICES.md"
VENV="${VENV:-backend/venv}"
TMP_PY="$(mktemp)"
TMP_JS="$(mktemp)"
trap 'rm -f "$TMP_PY" "$TMP_JS"' EXIT

status=0

# --- Backend (Python) ---------------------------------------------------------
PIP_LICENSES=""
if [ -x "$VENV/bin/pip-licenses" ]; then
    PIP_LICENSES="$VENV/bin/pip-licenses"
elif [ -x "$VENV/Scripts/pip-licenses.exe" ]; then
    PIP_LICENSES="$VENV/Scripts/pip-licenses.exe"
elif command -v pip-licenses >/dev/null 2>&1; then
    PIP_LICENSES="$(command -v pip-licenses)"
fi

if [ -z "$PIP_LICENSES" ]; then
    echo "error: pip-licenses not found (looked in $VENV and PATH)." >&2
    echo "       Install it into the backend venv:" >&2
    echo "         $VENV/bin/pip install pip-licenses" >&2
    echo "       or set VENV to a venv that has it, for example:" >&2
    echo "         VENV=/path/to/venv bash scripts/gen-third-party-notices.sh" >&2
    status=1
else
    if "$PIP_LICENSES" --format=markdown --with-urls >"$TMP_PY" 2>/dev/null && [ -s "$TMP_PY" ]; then
        echo "ok: collected Python license data via $PIP_LICENSES"
    else
        echo "error: pip-licenses failed to produce output" >&2
        : >"$TMP_PY"
        status=1
    fi
fi

# --- Frontend (npm production dependencies) ----------------------------------
if [ -d "frontend" ] && command -v npx >/dev/null 2>&1; then
    if (cd frontend && npx --yes license-checker-rseidelsohn --production --markdown) >"$TMP_JS" 2>/dev/null && [ -s "$TMP_JS" ]; then
        echo "ok: collected frontend license data via license-checker-rseidelsohn"
    else
        echo "error: license-checker-rseidelsohn failed (check npm registry access and that frontend dependencies are installed)" >&2
        : >"$TMP_JS"
        status=1
    fi
else
    echo "error: npx not found; install Node.js to collect frontend licenses" >&2
    status=1
fi

# --- Assemble ----------------------------------------------------------------
{
    echo "# Third-Party Notices"
    echo
    echo "This file lists third-party components distributed with ServerKit and their"
    echo "licenses. It is generated by \`scripts/gen-third-party-notices.sh\`; do not edit by hand."
    echo
    echo "Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo
    echo "See also \`LICENSE\`, \`NOTICE\` and \`CONTRIBUTORS.md\`."
    echo
    echo "## Backend (Python)"
    echo
    if [ -s "$TMP_PY" ]; then
        cat "$TMP_PY"
    else
        echo "_Not generated. See the error output of the generator script._"
    fi
    echo
    echo "## Frontend (npm, production dependencies)"
    echo
    if [ -s "$TMP_JS" ]; then
        cat "$TMP_JS"
    else
        echo "_Not generated. See the error output of the generator script._"
    fi
    echo
    echo "## Special licenses"
    echo
    echo "- IBM Plex fonts: SIL Open Font License 1.1, see \`frontend/public/fonts/LICENSE-IBM-PLEX.txt\`."
    echo "- Font Awesome icons (via react-icons): CC BY 4.0."
    echo "- Simple Icons brand logos (via react-icons/si): trademarks of their respective owners."
} >"$OUT"

echo "wrote $OUT"
exit "$status"
